"""WAF/CDN detection probe — identify web application firewalls and CDNs.

Detects the presence of Web Application Firewalls and CDNs that may
interfere with or block red team operations:
  1. Cloudflare detection
  2. AWS CloudFront / WAF detection
  3. Akamai detection
  4. Imperva / Incapsula detection
  5. Fastly detection
  6. ModSecurity detection
  7. Generic WAF behavior (403 patterns, challenge pages)
  8. CDN edge server identification
  9. Rate limiting behavior from WAF

Architecture:
  - Input: endpoints from session.report + target URL
  - Output: waf_info (detected WAF/CDN, headers, behavior)
  - Browser: False
"""

